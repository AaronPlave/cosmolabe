// ── geometry under test ─────────────────────────────────────────────────────

type Geometry = Record<Quantity, number>;
const DEG = 180 / Math.PI;
const toWest = (eastDeg: number) => (((-eastDeg % 360) + 360) % 360);
const wrap180 = (d: number) => ((((d + 180) % 360) + 360) % 360) - 180;

/** Planetographic latitude of a body-fixed surface point: the latitude of the
 *  ellipsoid normal there. */
function planetographicLat(p: Vec3, radii: number[]): number {
  const n = [p[0] / radii[0] ** 2, p[1] / radii[1] ** 2, p[2] / radii[2] ** 2];
  return Math.atan2(n[2], Math.hypot(n[0], n[1])) * DEG;
}

type Abcorr = NonNullable<GeometryConfig['abcorr']>;
type Method = NonNullable<GeometryConfig['subPointMethod']>;

/** The archive's quantities through `GeometryCalculator`, plus planetographic
 *  latitudes from the same sub-points (which it does not report). */
function calculatorGeometry(spice: SpiceInstance, row: ArchiveRow, abcorr: Abcorr, method: Method): Geometry {
  const et = spice.str2et(row.utcMid);
  const naifId = spice.bodn2c(row.target)!;
  const bodyFrame = `IAU_${row.target}`;
  const g = new GeometryCalculator(spice).compute(
    {
      bodyName: row.target,
      bodyFrame,
      naifId,
      observerName: 'CASSINI',
      abcorr,
      subPointMethod: method,
      computeIllumination: false,
      computeOrbitalElements: false,
      computeEarthAngles: false,
      computeBetaAngle: false,
      computeRADec: false,
      computeLST: false,
    },
    et,
  );
  const radii = spice.bodvcd(naifId, 'RADII');
  const so = spice.subpnt(method, row.target, et, bodyFrame, abcorr, 'CASSINI');
  const ss = spice.subslr(method, row.target, et, bodyFrame, abcorr, 'CASSINI');
  return {
    distanceKm: g.range!,
    subObserverLonW: toWest(g.subSCLongitude!),
    subObserverLatPc: g.subSCLatitude!,
    subObserverLatPg: planetographicLat(so.point, radii),
    subSolarLonW: toWest(g.subSolarLongitude!),
    subSolarLatPc: g.subSolarLatitude!,
    subSolarLatPg: planetographicLat(ss.point, radii),
    phaseDeg: g.sunBodySCAngle!,
  };
}

/** Residual (ours − archive) per quantity; longitudes wrapped to ±180°. */
function residuals(ours: Geometry, row: ArchiveRow): Geometry {
  const out = {} as Geometry;
  for (const q of Object.keys(SYMPTOM) as Quantity[]) {
    const d = ours[q] - row[q];
    out[q] = q.endsWith('LonW') ? wrap180(d) : d;
  }
  return out;
}

interface Worst {
  value: number;
  row: ArchiveRow;
}

/** Worst |residual| per quantity across a group's rows. */
function worstByQuantity(
  rows: ArchiveRow[],
  geometry: (row: ArchiveRow) => Partial<Geometry>,
): Partial<Record<Quantity, Worst>> {
  const worst: Partial<Record<Quantity, Worst>> = {};
  for (const row of rows) {
    const ours = geometry(row);
    const res = residuals(ours as Geometry, row);
    for (const q of Object.keys(ours) as Quantity[]) {
      const v = Math.abs(res[q]);
      if (!Number.isFinite(v)) throw new Error(`${row.opusId} ${row.target} ${q}: non-finite residual`);
      if (!worst[q] || v > worst[q]!.value) worst[q] = { value: v, row };
    }
  }
  return worst;
}

function describeWorst(q: Quantity, w: Worst): string {
  return `${q} (${SYMPTOM[q]}): worst ${w.value.toPrecision(3)} at ${w.row.opusId} ${w.row.utcMid}`;
}

