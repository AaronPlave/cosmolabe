describe('PDS geometry oracle: Universe composition (absolutePositionOf + rotationAt, light-time)', () => {
  let scene: BuiltScene;

  beforeAll(async () => {
    scene = await build(RECON_KERNELS);
  }, 60_000);

  it('uses SPICE rotations for every target, not the analytical fallback', () => {
    for (const name of ['Saturn', 'Titan', 'Mimas', 'Enceladus', 'Tethys', 'Dione', 'Rhea', 'Iapetus']) {
      expect(scene.universe.getBody(name)!.rotation?.constructor.name, name).toBe('SpiceRotation');
    }
  });

  for (const [group, targets] of Object.entries(GROUPS)) {
    describe(group, () => {
      const rows = ROWS.filter((r) => targets.includes(r.target));
      let worst: Partial<Record<Quantity, Worst>>;

      beforeAll(() => {
        worst = worstByQuantity(rows, (row) => universeGeometry(scene, row));
      });

      for (const [q, tol] of Object.entries(UNIVERSE_TOL[group]) as [Quantity, number][]) {
        it(`${q} within ${tol}${q === 'distanceKm' ? ' km' : '°'} over ${rows.length} rows`, () => {
          const w = worst[q]!;
          expect(w.value, describeWorst(q, w)).toBeLessThan(tol);
        });
      }
    });
  }

  describe('rejects the wrong compositions', () => {
    const saturn = ROWS.filter((r) => r.target === 'SATURN');

    it('without light time, Saturn sub-solar longitude leaves tolerance', () => {
      const w = worstByQuantity(saturn, (row) => ({
        subSolarLonW: universeGeometry(scene, row, { noLightTime: true }).subSolarLonW,
      })).subSolarLonW!;
      expect(w.value, describeWorst('subSolarLonW', w)).toBeGreaterThan(10 * UNIVERSE_TOL.Saturn.subSolarLonW!);
    });

    it('without the source→world frame step (the obliquity bug), Titan latitudes are degrees out', () => {
      // Titan's SPICE rotation is stated in J2000 (its trajectoryFrame), so
      // composing it into the ecliptic world needs the obliquity step. Saturn's
      // is not — it has no trajectoryFrame, so its rotation is already
      // ECLIPJ2000-sourced and this mutation would be a no-op there.
      expect(scene.universe.getBody('Titan')!.rotation!.sourceFrame).toBe('J2000');
      const titan = ROWS.filter((r) => r.target === 'TITAN');
      const w = worstByQuantity(titan, (row) => {
        const g = universeGeometry(scene, row, { noFrameStep: true });
        return { subObserverLatPc: g.subObserverLatPc, subSolarLatPc: g.subSolarLatPc };
      });
      expect(w.subObserverLatPc!.value, describeWorst('subObserverLatPc', w.subObserverLatPc!)).toBeGreaterThan(1);
      expect(w.subSolarLatPc!.value, describeWorst('subSolarLatPc', w.subSolarLatPc!)).toBeGreaterThan(1);
    });
  });
});
