/**
 * Layer 1b — a planetary archive as oracle (issue #28, Phase 1).
 *
 * `spice-oracle.test.ts` pins cosmolabe's composition to CSPICE's own. That is
 * necessary but circular: if cosmolabe and our own use of CSPICE agree on a
 * wrong convention — which frame, which aberration correction, which body
 * shape, what "sub-observer point" means — every tier passes. This one checks
 * against geometry somebody else composed: the PDS Ring-Moon Systems Node's
 * archived Cassini ISS geometry (the tables behind OPUS), computed by `oops`.
 * Not an independent ephemeris — it reads the same SPICE kernels — but an
 * independent *composition*, which is where cosmolabe has actually broken.
 *
 * 514 rows: every ISS frame of 2004 DOY 183–185 (Saturn orbit insertion) whose
 * target has an ephemeris in the SCPSE kernel — Saturn 299, Titan 197, and 18
 * across Mimas, Enceladus, Tethys, Dione, Rhea and Iapetus. Only the columns
 * that are independent of the camera's field of view are used, so no CK.
 *
 * Measured, not assumed (Phase 0, with every bound set from the worst residual
 * and re-measurable by zeroing it):
 *
 *   - The archive's convention is SPICE's `LT+S` and **INTERCEPT** sub-points.
 *     `GeometryCalculator`'s default `NEAR POINT` is off by 2.6° (sub-observer)
 *     and 4.15° (sub-solar) of latitude on Saturn — the planetocentric vs
 *     planetographic gap on an oblate body — and `NONE` puts Saturn's sub-solar
 *     longitude 0.059° out. Both are mutation guards below.
 *   - The trajectory has to be the reconstruction. The committed
 *     `040629AP_SCPSE_04179_04185.bsp` is a pre-burn predict; against it the
 *     Saturn range is 509 km out and Titan's sub-observer longitude 0.32°. The
 *     RMS node used `040909R_SCPSE_01066_04199.bsp` (Saturn range to 0.45 km);
 *     `scripts/make-cassini-soi-recon-spk.mjs` subsets it to these three days.
 *   - What remains is small and mostly systematic, and is pinned as measured
 *     rather than explained away: Saturn's sub-observer longitude carries a
 *     constant offset (+0.007° σ 0.001° under `LT+S`, +0.005° under `LT`) that
 *     its sub-solar longitude does not and that does not vary with range or
 *     time, and Titan's sub-solar latitude a constant +0.0019°. Neither is a
 *     timing or light-time effect; a pole or aberration-convention difference
 *     inside oops would fit, and is not established. Planetographic latitude
 *     is checked on Saturn only: the moons' residuals (to 0.1°) come from
 *     oops' choice of radii, not from composition.
 *
 * Two tiers, each grouped by body so a failure names its symptom: the CSPICE
 * calls behind `GeometryCalculator`, and the renderer's own composition
 * (`absolutePositionOf` + `rotationAt` + `composeBodyToWorldQuat`) with light
 * time applied by the test. Each carries mutation guards that must fail.
 *
 * Fixture: `__fixtures__/pds-geometry-soi.json`, regenerated by
 * `scripts/generate-pds-geometry-fixture.mjs`. Archive values are 3-decimal,
 * so ±0.0005° of every angular bound is quantization.
 */
