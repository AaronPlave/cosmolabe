// ── GeometryCalculator vs archive ───────────────────────────────────────────

describe('PDS geometry oracle: GeometryCalculator (CSPICE LT+S, intercept sub-points)', () => {
  let scene: BuiltScene;

  beforeAll(async () => {
    scene = await build(RECON_KERNELS);
  }, 60_000);

  it('the fixture covers the SOI window it claims to', () => {
    expect(ROWS.length).toBe(514);
    const counted = Object.values(GROUPS).flat();
    expect(ROWS.every((r) => counted.includes(r.target))).toBe(true);
  });

  for (const [group, targets] of Object.entries(GROUPS)) {
    describe(group, () => {
      const rows = ROWS.filter((r) => targets.includes(r.target));
      let worst: Partial<Record<Quantity, Worst>>;

      beforeAll(() => {
        worst = worstByQuantity(rows, (row) =>
          calculatorGeometry(scene.spice!, row, 'LT+S', 'INTERCEPT/ELLIPSOID'),
        );
      });

      for (const [q, tol] of Object.entries(CALCULATOR_TOL[group]) as [Quantity, number][]) {
        it(`${q} within ${tol}${q === 'distanceKm' ? ' km' : '°'} over ${rows.length} rows`, () => {
          const w = worst[q]!;
          expect(w.value, describeWorst(q, w)).toBeLessThan(tol);
        });
      }
    });
  }

  // Guards on the guard (cf. viewpoint-offset.test.ts): each mutation is a
  // convention this tier exists to pin. If any of them also passed, the bounds
  // above would be too loose to tell the conventions apart.
  describe('rejects the wrong conventions', () => {
    const saturn = ROWS.filter((r) => r.target === 'SATURN');
    const titan = ROWS.filter((r) => r.target === 'TITAN');

    it('without light-time (abcorr NONE), Saturn sub-solar longitude leaves tolerance', () => {
      const w = worstByQuantity(saturn, (row) => {
        const g = calculatorGeometry(scene.spice!, row, 'NONE', 'INTERCEPT/ELLIPSOID');
        return { subSolarLonW: g.subSolarLonW };
      }).subSolarLonW!;
      // Measured 0.059°: Saturn turns ~0.0094°/s and light time is 0.3–6 s.
      expect(w.value, describeWorst('subSolarLonW', w)).toBeGreaterThan(10 * CALCULATOR_TOL.Saturn.subSolarLonW!);
    });

    it('without stellar aberration (abcorr LT), Titan sub-solar longitude leaves tolerance', () => {
      const w = worstByQuantity(titan, (row) => {
        const g = calculatorGeometry(scene.spice!, row, 'LT', 'INTERCEPT/ELLIPSOID');
        return { subSolarLonW: g.subSolarLonW };
      }).subSolarLonW!;
      // Measured 0.0032°, against 0.0006° with it.
      expect(w.value, describeWorst('subSolarLonW', w)).toBeGreaterThan(2 * CALCULATOR_TOL.Titan.subSolarLonW!);
    });

    it('with near-point sub-points (the calculator default), Saturn latitudes are degrees out', () => {
      const w = worstByQuantity(saturn, (row) => {
        const g = calculatorGeometry(scene.spice!, row, 'LT+S', 'NEAR POINT/ELLIPSOID');
        return { subObserverLatPc: g.subObserverLatPc, subSolarLatPc: g.subSolarLatPc };
      });
      // Measured 2.8° and 4.15°.
      expect(w.subObserverLatPc!.value).toBeGreaterThan(1);
      expect(w.subSolarLatPc!.value).toBeGreaterThan(1);
    });

    it('against the pre-burn predict SPK, Saturn range leaves tolerance', async () => {
      const predict = await build(PREDICT_KERNELS);
      const w = worstByQuantity(saturn, (row) => {
        const g = calculatorGeometry(predict.spice!, row, 'LT+S', 'INTERCEPT/ELLIPSOID');
        return { distanceKm: g.distanceKm };
      }).distanceKm!;
      // Measured 509 km — why the reconstruction subset exists.
      expect(w.value, describeWorst('distanceKm', w)).toBeGreaterThan(100 * CALCULATOR_TOL.Saturn.distanceKm!);
    }, 60_000);
  });
});

// ── Universe (the renderer's composition) vs archive ────────────────────────

/** Speed of light, km/s — CSPICE's `clight_c`. */
const C_KM_S = 299792.458;

/**
 * The archive's quantities from what the renderer consumes —
 * `absolutePositionOf` (the frame chain), `rotationAt` and
 * `composeBodyToWorldQuat` (the J2000 obliquity step) — with one-way light time
 * applied here, since the Universe is geometric. Stellar aberration is not
 * applied, so the bounds below are the `LT` residuals, not `LT+S`.
 *
 * This is the path the obliquity (23.44°) and moon-displacement (73 km)
 * regressions broke. `spice-oracle.test.ts` pins it to CSPICE at the mm level;
 * this pins the pair of them to somebody else's answer.
 */
function universeGeometry(
  scene: BuiltScene,
  row: ArchiveRow,
  mutation: { noLightTime?: boolean; noFrameStep?: boolean } = {},
): Partial<Geometry> {
  const { universe, spice } = scene;
  const et = spice!.str2et(row.utcMid);
  const name = row.target[0] + row.target.slice(1).toLowerCase();
  const body = universe.getBody(name)!;
  const sub = (a: number[], b: number[]): Vec3 => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
  const norm = (v: number[]) => Math.hypot(v[0], v[1], v[2]);

  // Target as it was when the light Cassini sees left it.
  const observer = universe.absolutePositionOf('Cassini', et);
  let lt = 0;
  for (let i = 0; i < 3 && !mutation.noLightTime; i++) {
    lt = norm(sub(universe.absolutePositionOf(name, et - lt), observer)) / C_KM_S;
  }
  const etT = et - lt;
  const target = universe.absolutePositionOf(name, etT);
  // And the Sun as it was when the light that lit the target left it.
  let ltSun = 0;
  for (let i = 0; i < 3 && !mutation.noLightTime; i++) {
    ltSun = norm(sub(universe.absolutePositionOf('Sun', etT - ltSun), target)) / C_KM_S;
  }
  const sun = universe.absolutePositionOf('Sun', etT - ltSun);

  const toObserver = sub(observer, target);
  const toSun = sub(sun, target);
  const q = body.rotationAt(etT)!;
  // The mutation is the old viewpoint bug verbatim: conjugating `rotationAt`
  // and stopping at the model's own source frame (EquatorJ2000 here).
  const bodyToWorld = mutation.noFrameStep
    ? ([q[0], -q[1], -q[2], -q[3]] as [number, number, number, number])
    : composeBodyToWorldQuat(q, body.rotation!.sourceFrame, 'EclipticJ2000', etT);
  const worldToBody: [number, number, number, number] = [bodyToWorld[0], -bodyToWorld[1], -bodyToWorld[2], -bodyToWorld[3]];
  const latLon = (v: Vec3) => {
    const b = rotateVecByQuat(v, worldToBody);
    return { lat: Math.asin(b[2] / norm(b)) * DEG, lonW: toWest(Math.atan2(b[1], b[0]) * DEG) };
  };
  const so = latLon(toObserver);
  const ss = latLon(toSun);
  const cosPhase = (toObserver[0] * toSun[0] + toObserver[1] * toSun[1] + toObserver[2] * toSun[2]) / (norm(toObserver) * norm(toSun));
  return {
    distanceKm: norm(toObserver),
    subObserverLonW: so.lonW,
    subObserverLatPc: so.lat,
    subSolarLonW: ss.lonW,
    subSolarLatPc: ss.lat,
    phaseDeg: Math.acos(Math.min(1, Math.max(-1, cosPhase))) * DEG,
  };
}

